"""status_figure - the paper's figures of how much of CORA CORA.cpp has, and how much is bit-identical

The overview (a) has a bar per CORA group, split by status (bit-identical to CORALean, property
tests, ported, not ported), with the bit-identical share and "+n" out of scope after
it; (b) has the rows the ARCH-COMP instances execute, summed per instance, per category. The
appendix has the same bars per CORA class. The numbers are those of coverage/ (`benchmarks.py`'s
own summary), never re-derived; the colours are those of the paper's `cora-macs.sty`.

Syntax:   python scripts/paper/status_figure.py [--check]
Reads:    coverage/status.json, cora-inventory.json, coralean-status.json, out-of-scope.md,
          benchmarks.json, and the AFF/NLN/AINNCS tables of examples/benchmarks/README.md
Writes:   paper/generated/status.tikz and status-classes-<group>.tikz (the data only: the
          captions and the appendix text are the paper's own)
Checks:   --check compares the files on disk with what the tree gives now, and writes nothing
Exit code: 0 if the files are written (or current), else 1 with the stale files.

Authors:       Claude Opus 5.5
Written:       24-November-2026
Last update:   ---
Reviewed:      ---
"""
import argparse
import re
import sys
from pathlib import Path


# -----------------------------------------  BEGIN CODE  ----------------------------------------- #

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "coverage"))

import benchmarks as bm  # noqa: E402
import coverage as cov  # noqa: E402


REPO = bm.REPO
OUT_DIR = REPO / "paper" / "generated"
SOURCE = "% Generated by scripts/paper/status_figure.py from coverage/; do not edit."

# bar segments, left first, as (status, label, TikZ colour, rgb): CORA's reach-set gradient
SEGMENTS = [
    ("oracle", "certificate tests", "CORAcolorReachSet", (0.2706, 0.5882, 1.0)),
    ("property", "property tests", "CORAcolorReachSet!50!CORAcolorReachSet2", (0.4804, 0.7059, 1.0)),
    ("ported", "ported functionality", "CORAcolorReachSet2", (0.6902, 0.8235, 1.0)),
    ("todo", "not ported", "white", (1.0, 1.0, 1.0)),
]
# a status shown in another one's segment (the user, 2026-11-24: no untested segment; untested is ported)
MERGED = {"untested": "ported"}
# the ARCH categories, and the names of the groups in the figures
CATEGORIES = ("AFF", "NLN", "AINNCS")
LABEL = {"contSet": "Set representations", "contDynamics": "Cont. dynamics",
         "hybridDynamics": "Hybrid systems", "nn": "Neural networks",
         "specification": "Specification", "others": "Others"}
HEADING = {g: f"{LABEL[g].replace('Cont.', 'Continuous')} (\\texttt{{{g}}})" for g in LABEL}
# the appendix figures, one file each (the paper holds their floats and captions): (suffix, groups)
APPENDIX = [("sets", ("contSet",)), ("contdynamics", ("contDynamics",)),
            ("others", ("hybridDynamics", "nn")), ("specification", ("specification",)),
            ("misc", ("others",))]
# the sizes, in cm unless named otherwise, and the fonts and greys of the figures
LINEWIDTH_CM = 12.2  # LNCS text width: which segments are wide enough for their number
MONO = "\\ttfamily\\scriptsize"
CHAR_W = 0.13  # cm per character of MONO
MIN_SEG = 0.04  # cm: the narrowest a non-empty segment is drawn, so it stays visible
OUTLINE = "0.2pt"
GREY = "black!40"
LEGEND = ("legend style={legend cell align=left, align=left, draw=white!15!black, rounded corners, "
          "font=\\scriptsize, inner sep=1.5pt, /tikz/every even column/.append style={column sep=0.5ex}, "
          "/tikz/every odd column/.append style={column sep=0pt}},\n    legend image code/.code={\\draw[#1, "
          "draw=black, line width=" + OUTLINE + ", rounded corners=1pt] (0cm,-0.6ex) rectangle (1.2ex,0.6ex);}")
PREAMBLE = """\\begin{tikzpicture}
\\footnotesize
\\pgfplotsset{every axis/.append style={scale only axis,
    y dir=reverse, enlarge y limits={abs=0.7}, xmin=0}}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="compare the files on disk, write nothing")
    args = parser.parse_args()
    # --check compares, else the files are written
    expected = outputs(load())
    if args.check:
        stale = [name for name, text in expected.items()
                 if not (OUT_DIR / name).exists() or (OUT_DIR / name).read_text(encoding="utf-8") != text]
        for name in stale:
            print(f"  paper/generated/{name} is stale; run python scripts/paper/status_figure.py")
        return 1 if stale else 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in expected.items():
        (OUT_DIR / name).write_text(text, encoding="utf-8")
    print(f"status_figure: wrote {len(expected)} files under paper/generated/")
    return 0


# -----------------------------------------  AUXILIARY  ------------------------------------------ #

def load():
    """The data of every figure: per group and class the counts by status, and per ARCH category
    the executed rows that can be bit-exact, by status."""
    inventory = cov.load_json(REPO / "coverage" / "cora-inventory.json")
    groups = inventory["groups"]
    status = cov.load_json(REPO / "coverage" / "status.json")["rows"]
    lean = cov.load_json(REPO / "coverage" / "coralean-status.json").get("rows", {})
    apart, _ = cov.ledger_of(REPO, groups, cov.APART)
    classes = {g: {c: count([cov.cora_rows.key_of(g, c, m) for m in ms], status)
                   for c, ms in groups[g].items()} for g in cov.GROUP_ORDER}
    totals = {g: count([k for k in status if k.split("/")[0] == g], status) for g in cov.GROUP_ORDER}
    measured = dict(sorted(cov.load_json(REPO / "coverage" / "benchmarks.json")["instances"].items()))
    summary = bm.summarize(measured, status, groups, REPO, lean, apart)
    return {"classes": classes, "totals": totals, "arch": arch(summary, lean, apart)}


def count(keys, status):
    """`{status: n}` of some rows, the out-of-scope ones under `out`."""
    out = {s: sum(MERGED.get(status[k], status[k]) == s for k in keys) for s, *_ in SEGMENTS}
    out["out"] = sum(status[k] == cov.OUT for k in keys)
    return out


def share(c):
    """The bit-identical share of the rows in scope, in percent."""
    scope = sum(c[s] for s, *_ in SEGMENTS)
    return 100 * c["oracle"] / scope if scope else 0.0


def categories(names):
    """The ARCH category of each instance, from the section of the benchmark README whose main table
    names it; a `-script` variant goes with its instance. An instance of no category fails the run."""
    found, section = {}, None
    for line in (REPO / "examples" / "benchmarks" / "README.md").read_text(encoding="utf-8").split("\n"):
        if line.startswith("## "):
            match = re.match(r"## (\w+) results", line)
            section = match.group(1) if match and match.group(1) in CATEGORIES else None
        elif section and line.startswith("| ") and not line.startswith("| instance"):
            key = bm.readme_instance(line.split("|")[1].strip(), names)
            if key:
                found[key] = section
    for name in names:
        if name not in found and name.removesuffix("-script") in found:
            found[name] = found[name.removesuffix("-script")]
    missing = [name for name in names if name not in found]
    if missing:
        sys.exit(f"status_figure: no ARCH category for {', '.join(missing)} in examples/benchmarks/README.md")
    return found


def arch(summary, lean, apart):
    """Per category: the instances and, summed per instance, the rows that can be bit-exact by status.
    The rows left out are `summarize`'s (plumbing, out of scope here or in CORALean); its counts of
    bit-exact and eligible rows must come out the same, else the rule here drifted from it."""
    done = {k: s for k, s in summary.items() if "rows" in s}
    which = categories(list(summary))
    out = {c: {"instances": 0, **{s: 0 for s, *_ in SEGMENTS}} for c in CATEGORIES}
    for name, s in done.items():
        rows = {k: v for k, v in s["rows"].items() if v != cov.OUT and not bm.is_plumbing(k)
                and k not in apart and lean.get(k, {}).get("status") != "out-of-scope"}
        if sum(v == "oracle" for v in rows.values()) != s["oracle"] or len(rows) != s["eligible"]:
            sys.exit(f"status_figure: the eligible rows of {name} differ from benchmarks.py's")
        entry = out[which[name]]
        entry["instances"] += 1
        for v in rows.values():
            entry[MERGED.get(v, v)] += 1
    return out


def bar(i, c, scale, half, sharp_left):
    """The TikZ of one stacked bar at row `i`: the fills clipped to one thin rounded outline, and the
    numbers of the segments wide enough for them; returns `(fills, numbers, end)`."""
    widths = {s: max(c[s], MIN_SEG / scale) if c[s] else 0 for s, *_ in SEGMENTS}
    end = sum(widths.values())
    lo, hi = f"[yshift=-{half:g}pt]axis cs:", f"[yshift={half:g}pt]axis cs:"
    r = f"{min(1.5, half / 2):g}pt"
    # square on the left where the bar meets the frame of the axis
    shape = (f"({lo}0,{i}) [rounded corners={r}] -- ({lo}{end:g},{i}) -- ({hi}{end:g},{i}) "
             f"[sharp corners] -- ({hi}0,{i}) -- cycle" if sharp_left
             else f"[rounded corners={r}] ({lo}0,{i}) rectangle ({hi}{end:g},{i})")
    # the fills, left to right, and the numbers of the segments wide enough for them
    fills, numbers, start = [f"\\begin{{scope}}\\clip{shape};"], [], 0
    for s, _, colour, rgb in SEGMENTS:
        v, w = c[s], widths[s]
        if v:
            fills.append(f"\\fill[{colour}] ({lo}{start:g},{i}) rectangle ({hi}{start + w:g},{i});")
        text = c.get("text", {}).get(s, str(v))
        if v and len(text) * CHAR_W + 0.06 <= w * scale:
            ink = "white" if 0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2] < 0.6 else "black"
            text = text.replace("%", "\\%")
            numbers.append(f"\\node[font={MONO}, text={ink}, inner sep=0pt] at (axis cs:{start + w / 2:g},{i}) "
                           f"{{{text}}};")
        start += w
    fills += ["\\end{scope}", f"\\draw[black, line width={OUTLINE}] {shape};"]
    return fills, numbers, end


def panel(name, entries, opts, width_cm, xmax, half, framed, legend=None, columns=5):
    """One pgfplots axis of stacked bars. `entries` is `[(label, counts, tail)]`: `counts` is None for
    a heading row; `tail` the text after the bar. The numbers go on a second axis over the first, as
    the fills would cover nodes in it."""
    # the options of the axis: the row labels, the frame or none, the legend
    n = len(entries)
    head = [f"name={name}", *opts, f"xmax={xmax}", "clip=false", "scaled ticks=false",
            f"ytick={{{','.join(str(i) for i in range(n))}}}",
            "yticklabels={" + ",".join("{" + label + "}" for label, _, _ in entries) + "}",
            "ytick style={draw=none}", "yticklabel style={font=\\scriptsize}"]
    if framed:
        head += ["rounded axis", "xtick pos=bottom", "tick label style={font=\\scriptsize}",
                 "xmajorgrids=true", "major x grid style={draw=black!15, line width=0.4pt}"]
    else:
        head += ["axis line style={draw=none}", "xtick=\\empty", "tick style={draw=none}"]
    if legend:
        head += [f"legend columns={columns}, legend to name={legend}", LEGEND]
    out = ["\\begin{axis}[" + ",\n    ".join(head) + "]",
           f"\\addplot[draw=none, forget plot] coordinates {{(0,0) (0,{n - 1})}};"]
    for _, label, colour, _ in SEGMENTS if legend else []:
        out += [f"\\addlegendimage{{fill={colour}}}", f"\\addlegendentry{{{label}}}"]
    # the bars, and the text after each
    numbers = []
    for i, (_, c, tail) in enumerate(entries):
        if c is None:
            continue
        fills, nums, end = bar(i, c, width_cm / xmax, half, framed)
        out += fills
        numbers += nums
        out.append(f"\\node[anchor=west, font={MONO}, inner sep=3pt] at (axis cs:{end:g},{i}) {{{tail}}};")
    out.append("\\end{axis}")
    if numbers:
        size = [o for o in opts if o.startswith(("height=", "width="))]
        out.append(f"\\begin{{axis}}[at={{({name}.south west)}}, anchor=south west, {', '.join(size)}, "
                   f"xmax={xmax}, hide axis, clip=false]")
        out.append(f"\\addplot[draw=none] coordinates {{(0,0) (0,{n - 1})}};")
        out += numbers
        out.append("\\end{axis}")
    return "\n".join(out)


def room(entries, width_cm):
    """The least round `xmax` (a multiple of 10, 50 or 100 by its size) at which every bar and the
    text after it stay inside an axis `width_cm` wide."""
    need = 0
    for _, c, text in entries:
        if c is not None:
            chars = len(re.sub(r"\\hspace\{[^}]*\}|\\textcolor\{[^}]*\}|[{}\\]", "", text)) + 2
            end = sum(c[s] for s, *_ in SEGMENTS)
            need = max(need, end * width_cm / (width_cm - chars * CHAR_W - 0.2))
    step = 10 if need < 100 else 50 if need < 500 else 100
    return step * (1 + int(need) // step)


def tail(c):
    """After a bar of CORA methods: the bit-identical share, and the methods out of scope in grey."""
    out = f"\\hspace{{0.8em}}\\textcolor{{{GREY}}}{{+{c['out']}}}" if c["out"] else ""
    return f"{share(c):.0f}\\%{out}"


def overview(data):
    """The main figure: (a) the CORA groups on the left, (b) the ARCH categories on the right."""
    # the bars of (a), one per group
    groups = [(LABEL[g], data["totals"][g], tail(data["totals"][g])) for g in cov.GROUP_ORDER]
    # (a): the groups, its width a half line less its labels
    lab_a, lab_b = 2.55, 1.1  # the width of the row labels, in cm
    wa = 0.50 * LINEWIDTH_CM - lab_a
    xmax = room(groups, wa)
    a = panel("groups", groups, [f"at={{({lab_a}cm,0cm)}}", "anchor=north west", "height=3.0cm",
                                 f"width=0.50\\linewidth-{lab_a}cm", "title={(a)}",
                                 f"title style={{at={{(0.5,1)}}, xshift=-{lab_a / 2:g}cm, yshift=0.5ex, "
                                 "anchor=south, font=\\footnotesize}"],
              wa, xmax, 5.5, True)
    # (b): the categories in percent, beside (a), with the shared legend below it
    rows = []
    for k in CATEGORIES:
        c = dict(data["arch"][k])
        total = sum(c[s] for s, *_ in SEGMENTS)
        pct = {s: 100 * c[s] / total for s, *_ in SEGMENTS}
        pct["out"], pct["text"] = 0, {"oracle": f"{pct['oracle']:.1f}%"}
        rows.append((k, pct, f"{c['oracle']}/{total}"))
    tail_b = 3 / 28.45 + CHAR_W * max(len(t) for *_, t in rows) + 0.03
    wb = 0.40 * LINEWIDTH_CM - lab_b - tail_b
    b = panel("arch", rows, [f"at={{(0.59\\linewidth+{lab_b}cm,0cm)}}", "anchor=north west", "height=1.6cm",
                             f"width={wb:.2f}cm", "title={(b)}",
                             f"title style={{at={{(0.5,1)}}, xshift={(tail_b - lab_b) / 2:.3f}cm, yshift=0.5ex, "
                             "anchor=south, font=\\footnotesize}"],
              wb, 100, 5.5, False, legend="statuslegend", columns=2)
    # the picture: (a), (b) and the legend under (b)
    return f"""{SOURCE}
% (a) CORA functions per group by how CORA.cpp tests them, with the bit-identical share and "+n" out of
% scope after each bar; (b) the rows the ARCH-COMP instances execute (summed per instance, constructors,
% accessors and the rows CORALean does not formalize left out), in percent, with "bit-identical/all"
% after each bar. Sized in \\linewidth; no \\resizebox.
{PREAMBLE}
{a}

{b}

\\node[anchor=north, inner sep=0pt] at ([xshift={(tail_b - lab_b) / 2:.3f}cm, yshift=-0.4cm]arch.south)
    {{\\ref*{{statuslegend}}}};
\\end{{tikzpicture}}
"""


def classes_figure(groups, data, legend):
    """An appendix figure: a bar per CORA class, under an italic heading per group."""
    entries = []
    for g in groups:
        entries.append(("\\textit{" + HEADING[g] + "}", None, None))
        entries += [("\\texttt{" + c + "}", v, tail(v)) for c, v in data["classes"][g].items()]
    xmax = room(entries, 0.5 * LINEWIDTH_CM)
    body = panel("classes", entries, [f"height={0.3 * len(entries):.2f}cm", "width=0.5\\linewidth"],
                 0.5 * LINEWIDTH_CM, xmax, 2.5, True, legend=legend)
    return f"""{SOURCE}
% CORA methods per class by how CORA.cpp tests them, with the bit-identical share and "+n" out of scope.
{PREAMBLE}
{body}

\\node[anchor=north, yshift=-1ex] at (current bounding box.south) {{\\ref*{{{legend}}}}};
\\end{{tikzpicture}}
"""


def outputs(data):
    """Every generated file, `{name under paper/generated: text}`."""
    out = {"status.tikz": overview(data)}
    for suffix, groups in APPENDIX:
        out[f"status-classes-{suffix}.tikz"] = classes_figure(groups, data, f"classlegend{suffix}")
    return out


if __name__ == "__main__":
    sys.exit(main())

