HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import coverage as cov  # noqa: E402


REPO = HERE.parents[1]
STATUSES = cov.STATUSES + (cov.OUT,)
BEGIN, END = "<!-- BEGIN bit-exact -->", "<!-- END bit-exact -->"
HEADER = """# What the benchmarks run, and how much of it is bit-exact against CORALean

Generated by `scripts/coverage/benchmarks.py` from a coverage build of the benchmark instances and
the tags of the sources; never edited by hand (CONTRIBUTING.md, "Coverage"). A row counts for an
instance if a source file tagged with it executed a line; the counts are file-level and approximate
(built with -O2, inlined code may count toward the caller). `oracle` means the operation is bit-exact
on its test inputs, not on this benchmark's exact path. Statuses are those of `status.json`.
"""


def parse_gcov(text, root):
    """The files of `gcov --json-format --stdout` output with an executed line, relative to `root`."""
    decoder, position, executed = json.JSONDecoder(), 0, set()
    root = Path(root).resolve()
    while True:
        position = text.find("{", position)
        if position < 0:
            return sorted(executed)
        document, position = decoder.raw_decode(text, position)
        base = Path(document.get("current_working_directory", "."))
        for entry in document.get("files", []):
            path = Path(entry["file"])
            path = (path if path.is_absolute() else base / path).resolve()
            try:
                relative = path.relative_to(root).as_posix()
            except ValueError:
                continue
            if relative.startswith(("src/", "include/")) and any(
                    line.get("count", 0) > 0 for line in entry.get("lines", [])):
                executed.add(relative)


def rows_of_files(root, files, groups):
    """`(rows, only)`: the row keys the tags of the files name, and the files with no CORA counterpart."""
    rows, only = [], []
    for name in files:
        path = Path(root) / name
        keys = [key for kind, tag, _ in cov.tags_of(Path(root), path, True) if kind == "CORA"
                for key, error in [cov.resolve(tag, groups)] if key and not error]
        if keys:
            rows.extend(keys)
        elif cov.has_only(path):
            only.append(name)
    return sorted(set(rows)), only


def summarize(measured, status, groups, root):
    """Per instance: the rows with their status, the files without a counterpart, and the counts."""
    out = {}
    # an instance that was not measured says why
    for name, entry in measured.items():
        if "files" not in entry:
            out[name] = {"skipped": entry.get("skipped", "not measured")}
            continue
        rows, only = rows_of_files(root, entry["files"], groups)
        states = {key: status.get(key, "todo") for key in rows}
        counts = {s: sum(v == s for v in states.values()) for s in STATUSES}
        out[name] = {"rows": states, "only": only, "counts": counts, "total": len(rows),
                     "oracle": counts["oracle"]}
    return out


def render_markdown(summary, lean):
    """coverage/benchmarks.md."""
    lines = [HEADER, "## Per instance", "",
             "| instance | rows | oracle | property | ported | untested | todo | out of scope | bit-exact |",
             "|---|---|---|---|---|---|---|---|---|"]
    for name, s in summary.items():
        if "skipped" in s:
            lines.append(f"| {name} | not measured: {s['skipped']} | | | | | | | |")
            continue
        c = s["counts"]
        lines.append(f"| {name} | {s['total']} | {c['oracle']} | {c['property']} | {c['ported']} | "
                     f"{c['untested']} | {c['todo']} | {c[cov.OUT]} | {s['oracle']}/{s['total']} |")
    # the rows that are not bit-exact, with the instances that run them
    blocked = {}
    for name, s in summary.items():
        for key, state in s.get("rows", {}).items():
            if state != "oracle":
                blocked.setdefault(key, []).append(name)
    # the aggregate: the rows that block the most instances come first
    lines += ["", "## Rows that are not bit-exact, by the number of instances they touch", "",
              "The to-do list for CORALean batches: `CORALean` is what CORALean has for the row "
              "(coralean-status.json).", "",
              "| row | status | CORALean | instances | which |", "|---|---|---|---|---|"]
    for key, names in sorted(blocked.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        state = next(s["rows"][key] for s in summary.values() if key in s.get("rows", {}))
        lines.append(f"| `{key}` | {state} | {lean.get(key, {}).get('status', '-')} | {len(names)} | "
                     f"{', '.join(names)} |")
    # the files without a CORA counterpart, with the number of instances that run them
    lines += ["", "## Files with no CORA counterpart", ""]
    apart = {}
    for name, s in summary.items():
        for file in s.get("only", []):
            apart.setdefault(file, []).append(name)
    lines += [f"- `{file}`: {len(names)} instances" for file, names in sorted(apart.items())]
    lines += ["", "## Per instance, the rows that are not bit-exact", ""]
    for name, s in summary.items():
        if "rows" not in s:
            continue
        rest = [f"`{k}` ({v})" for k, v in sorted(s["rows"].items()) if v != "oracle"]
        lines += [f"<details><summary>{name}: {s['oracle']}/{s['total']}</summary>", "",
                  ", ".join(rest) if rest else "none", "", "</details>", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_table(summary):
    """The table of the README: bit-exact rows per instance."""
    lines = ["| instance | bit-exact vs CORALean | not bit-exact |", "|---|---|---|"]
    for name, s in summary.items():
        if "skipped" in s:
            lines.append(f"| {name} | - | not measured |")
        else:
            lines.append(f"| {name} | {s['oracle']}/{s['total']} | {s['total'] - s['oracle']} |")
    return "\n".join(lines)


def splice(readme, table):
    """The README with the table between its markers (the markers are added at the end if missing)."""
    block = f"{BEGIN}\n{table}\n{END}"
    if BEGIN in readme and END in readme:
        head, _, rest = readme.partition(BEGIN)
        _, _, tail = rest.partition(END)
        return head + block + tail
    return readme.rstrip("\n") + "\n\n" + block + "\n"


# Measuring ---------------------------------------------------------------------------------------

# gcov, not a trace at `detail::Entry`: the private steps (`priv_*`) carry tags and never pass an entry.

def instances(build):
    """The names of the `benchmark` tests of the build, in ctest's order."""
    listing = subprocess.run(["ctest", "--test-dir", str(build), "-N", "-L", "benchmark"], text=True,
                             capture_output=True, check=True).stdout
    return re.findall(r"Test\s+#\d+: benchmark/(\S+)", listing)


def gcov_files(build, root):
    """The files that the counters of the build say executed a line."""
    notes = sorted(Path(build).rglob("*.gcda"))
    executed = set()
    for start in range(0, len(notes), 100):
        out = subprocess.run(["gcov", "--json-format", "--stdout", *map(str, notes[start:start + 100])],
                             text=True, capture_output=True, cwd=build).stdout
        executed.update(parse_gcov(out, root))
    return sorted(executed)


def measure(root, build, names, timeout):
    """`{instance: {"files": [...]}}` or `{"skipped": reason}` from running each on its own."""
    measured = {}
    for name in names:
        for counter in Path(build).rglob("*.gcda"):
            counter.unlink()
        # its own process group, so that a timeout stops the program and not only ctest
        process = subprocess.Popen(["ctest", "--test-dir", str(build), "-R", f"^benchmark/{name}$",
                                    "--timeout", str(timeout)], text=True, stdout=subprocess.DEVNULL,
                                   start_new_session=True)
        try:
            code = process.wait(timeout=timeout + 30)
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGKILL)
            code = -1
        if code != 0:
            measured[name] = {"skipped": f"failed or over {timeout} s"}
            continue
        measured[name] = {"files": gcov_files(build, root)}
        print(f"{name}: {len(measured[name]['files'])} files", flush=True)
    return measured


def build_programs(root, preset):
    """Configures and builds the benchmark programs of the preset `coverage`."""
    targets = sorted(p.stem for p in (Path(root) / "examples/cpp/benchmarks").glob("benchmark_*.cpp"))
    subprocess.run(["cmake", "--preset", preset], cwd=root, check=True)
    subprocess.run(["cmake", "--build", "--preset", preset, "--target", *targets], cwd=root, check=True)


# ============================================  MAIN  ============================================ #

def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="measure again and compare, write nothing")
    parser.add_argument("--render-only", action="store_true", help="render the committed measurement")
    parser.add_argument("--only", action="append", default=[], help="measure just this instance")
    parser.add_argument("--timeout", type=int, default=600, help="seconds per instance (default 600)")
    parser.add_argument("--build-dir", default="build/coverage")
    args = parser.parse_args()
    # the instances come from a measurement, or from the committed file (--render-only)
    root = REPO
    data = root / "coverage" / "benchmarks.json"
    committed = cov.load_json(data)
    if args.render_only:
        measured = committed.get("instances", {})
    else:
        build_programs(root, "coverage")
        build = root / args.build_dir
        measured = measure(root, build, args.only or instances(build), args.timeout)
        if args.only:
            measured = {**committed.get("instances", {}), **measured}
    inventory = cov.load_json(root / "coverage" / "cora-inventory.json")
    status = cov.load_json(root / "coverage" / "status.json").get("rows", {})
    lean = cov.load_json(root / "coverage" / "coralean-status.json").get("rows", {})
    summary = summarize(measured, status, inventory["groups"], root)
    # the files to write, by path
    expected = {
        data: json.dumps({"instances": measured}, indent=1, sort_keys=True) + "\n",
        root / "coverage" / "benchmarks.md": render_markdown(summary, lean),
        root / "examples" / "benchmarks" / "README.md": splice(
            (root / "examples" / "benchmarks" / "README.md").read_text(encoding="utf-8"),
            render_table(summary)),
    }
    if args.check:
        stale = [p.relative_to(root).as_posix() for p, text in expected.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        for name in stale:
            print(f"  {name} is stale; run python scripts/coverage/benchmarks.py")
        return 1 if stale else 0
    for path, text in expected.items():
        path.write_text(text, encoding="utf-8")
    print("benchmarks: wrote coverage/benchmarks.json, coverage/benchmarks.md and the README table")
    return 0


if __name__ == "__main__":
    sys.exit(main())

