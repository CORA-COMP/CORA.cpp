HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import coverage as cov  # noqa: E402


REPO = HERE.parents[1]
STATUSES = cov.STATUSES + (cov.OUT,)
BEGIN, END = "<!-- BEGIN bit-exact -->", "<!-- END bit-exact -->"
OVERALL_BEGIN, OVERALL_END = "<!-- BEGIN overall -->", "<!-- END overall -->"
# The text that coverage/benchmarks.md starts with
HEADER = """# What the benchmarks run, and how much of it is bit-exact against CORALean

Generated by `scripts/coverage/benchmarks.py` from a coverage build of the benchmark instances and
the tags of the sources; never edited by hand (CONTRIBUTING.md, "Coverage"). A row counts for an
instance if a source file tagged with it executed a line; the counts are file-level and approximate
(built with -O2, inlined code may count toward the caller). `oracle` means the operation is bit-exact
on its test inputs, not on this benchmark's exact path. Statuses are those of `status.json`.
A row that CORALean marks out of scope (`coralean-status.json`), or that CORA.cpp's ledger does, can
never become `oracle`: it has a column of its own and is left out of the bit-exact denominator, as
are the plumbing rows (constructors and accessors, `is_plumbing`; no operation to compare).
A header counts a row only if the .cpp file that implements it executed a line.
"""


# What keeps the rows of each family from `oracle`: one entry each, written by hand.
WHY = """## What keeps the rows of each family from `oracle`

- Linear verify (CBC, CBF, HEAT01/02, ISS, RAND): the oracle serves no `linearSys.verify` (CORALean's
  `verifyFloat` takes the reach function and the distance routines as arguments), and its reach is
  CORALean's algorithm, not CORA's step (the tests compare by tolerance: `property`). The classes
  `zonotope`, `contSet`, `polytope` are constructors and accessors: no op to compare.
- HEAT03, HEAT04, RND02, RND04-06: the subspaces are CORALean's float definitions (bit-exact, `test_lean_krylov`); the
  restart windows, their lifting and the assembly of `linearSys/reach` and of the support function bound are not
  (docs/oracle-requests.md).
- Platoon (PLA): `linParamSys` `initReach`/`post` are CORALean's own mapping-matrix algorithm, not CORA's;
  `expmOneParam` is only `bound`.
- Hybrid (SRA, GRBX, DTN, BRK, SPRE22): `hybridAutomaton/reach` is not served (the oracle has the location
  and transition steps), and `guardIntersect` follows CORALean's dual bound, not CORA's dichotomic search.
- Nonlinear (TRAF22, SPRE22): the `lin` step at tensor order 2 is CORALean's `linReachFloat` (the region
  step, bit for bit: `test_lean_nonlinear_sys_lin_reach`). AINNCS instances on polynomial zonotopes
  step CORALean's `linReachPolyLoopFloat` (`priv_lin_reach_poly`, bit for bit:
  `test_lean_nonlinear_sys_lin_reach_poly`), reduced by `reduceCora` in `post`.
"""


# The rows of the README tables whose name differs from the instance of the benchmark program.
ROW_NAMES = {"Unicycle reach, with the report's disturbance w": "Unicycle-reach-disturbance",
             "Double Pendulum less-robust, the script (no splitting)": "Double_Pendulum-less-robust-script",
             "Docking constraint, polytope and splitting": "Docking-constraint-polygon",
             "CartPole reach, the report's set": "CartPole-reach-report"}

# Plumbing rows (no operation to compare): constructors and accessors, counted apart (coverage/README.md).
PLUMBING_METHODS = {"dim", "generators", "numgens", "isemptyobject", "representsa_emptyObject",
                    "reorder"}


def is_plumbing(key):
    """Whether the row `group/class/method` is plumbing: a constructor or an accessor."""
    parts = key.split("/")
    return len(parts) == 3 and (parts[2] == parts[1] or parts[2] in PLUMBING_METHODS)


def parse_gcov(text, root):
    """The files of `gcov --json-format --stdout` output with an executed line, relative to `root`."""
    decoder, position, executed = json.JSONDecoder(), 0, set()
    root = Path(root).resolve()
    while True:
        position = text.find("{", position)
        if position < 0:
            return sorted(executed)
        document, position = decoder.raw_decode(text, position)
        base = Path(document.get("current_working_directory", "."))
        for entry in document.get("files", []):
            path = Path(entry["file"])
            path = (path if path.is_absolute() else base / path).resolve()
            try:
                relative = path.relative_to(root).as_posix()
            except ValueError:
                continue
            if relative.startswith(("src/", "include/")) and any(
                    line.get("count", 0) > 0 for line in entry.get("lines", [])):
                executed.add(relative)


def file_rows(root, name, groups):
    """The row keys that the CORA tags of one file name."""
    path = Path(root) / name
    return [key for kind, tag, _ in cov.tags_of(Path(root), path, True) if kind == "CORA"
            for key, error in [cov.resolve(tag, groups)] if key and not error]


def private_steps(root, name):
    """The private CORA files (`.../private/priv_*.m`) that one file names; they have no row."""
    path = Path(root) / name
    return [tag for kind, tag, _ in cov.tags_of(Path(root), path, True)
            if kind == "CORA" and "/private/" in tag]


def implemented_rows(root, groups):
    """The rows that some .cpp file of src/ is tagged with: a header may name them too."""
    return {key for path in sorted((Path(root) / "src").rglob("*.cpp"))
            for key in file_rows(root, path.relative_to(root).as_posix(), groups)}


def rows_of_files(root, files, groups):
    """`(rows, only)`: the rows the tags of the files name, and the files with no CORA counterpart."""
    # a header counts a row that a .cpp file implements only if that file executed a line
    implemented, executed = implemented_rows(root, groups), set()
    for name in files:
        if name.endswith(".cpp"):
            executed.update(file_rows(root, name, groups))
    rows, only = [], []
    for name in files:
        keys = file_rows(root, name, groups)
        if name.endswith(".h"):
            keys = [key for key in keys if key not in implemented or key in executed]
        if keys:
            rows.extend(keys)
        elif cov.has_only(Path(root) / name):
            only.append(name)
    return sorted(set(rows)), only


def summarize(measured, status, groups, root, lean=None):
    """Per instance: the rows with their status, the files without a counterpart, and the counts."""
    # rows out of scope in CORALean are counted apart (lean_out) and leave the denominator (eligible)
    out, lean = {}, lean or {}
    # an instance that was not measured says why
    for name, entry in measured.items():
        if "files" not in entry:
            out[name] = {"skipped": entry.get("skipped", "not measured")}
            continue
        rows, only = rows_of_files(root, entry["files"], groups)
        states = {key: status.get(key, "todo") for key in rows}
        counts = {s: sum(v == s for v in states.values()) for s in STATUSES}
        beyond = [key for key, v in states.items()
                  if v != cov.OUT and lean.get(key, {}).get("status") == "out-of-scope"]
        plumbing = [key for key, v in states.items()
                    if is_plumbing(key) and v != cov.OUT and key not in beyond]
        steps = sorted({tag for file in entry["files"] if file.endswith(".cpp")
                        for tag in private_steps(root, file)})
        done = sum(states[key] == "oracle" for key in plumbing)
        # the rows that only a property test backs, of those that can be bit-exact
        excluded = set(plumbing) | set(beyond)
        weaker = sum(v == "property" for key, v in states.items() if key not in excluded)
        out[name] = {"rows": states, "only": only, "counts": counts, "total": len(rows),
                     "oracle": counts["oracle"] - done, "lean_out": len(beyond), "steps": steps,
                     "plumbing": len(plumbing), "property": weaker,
                     "eligible": len(rows) - counts[cov.OUT] - len(beyond) - len(plumbing)}
    return out


def render_markdown(summary, lean):
    """coverage/benchmarks.md."""
    lines = [HEADER, render_overall(summary), "", "## Per instance", "",
             "| instance | rows | oracle | property | ported | untested | todo | out of scope | "
             "CORALean out of scope | plumbing | bit-exact |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, s in summary.items():
        if "skipped" in s:
            lines.append(f"| {name} | not measured: {s['skipped']} | | | | | | | | | |")
            continue
        c = s["counts"]
        lines.append(f"| {name} | {s['total']} | {c['oracle']} | {c['property']} | {c['ported']} | "
                     f"{c['untested']} | {c['todo']} | {c[cov.OUT]} | {s['lean_out']} | "
                     f"{s['plumbing']} | {s['oracle']}/{s['eligible']} |")
    # the rows that are not bit-exact, with the instances that run them
    blocked = {}
    for name, s in summary.items():
        for key, state in s.get("rows", {}).items():
            if state != "oracle" and not is_plumbing(key):
                blocked.setdefault(key, []).append(name)
    # the aggregate: the rows that block the most instances come first
    lines += ["", "## Rows that are not bit-exact, by the number of instances they touch", "",
              "The to-do list for CORALean batches: `CORALean` is what CORALean has for the row "
              "(coralean-status.json).", "",
              "| row | status | CORALean | instances | which |", "|---|---|---|---|---|"]
    for key, names in sorted(blocked.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        state = next(s["rows"][key] for s in summary.values() if key in s.get("rows", {}))
        lines.append(f"| `{key}` | {state} | {lean.get(key, {}).get('status', '-')} | {len(names)} | "
                     f"{', '.join(names)} |")
    # the files without a CORA counterpart, with the number of instances that run them
    lines += ["", "## Files with no CORA counterpart", ""]
    apart = {}
    for name, s in summary.items():
        for file in s.get("only", []):
            apart.setdefault(file, []).append(name)
    lines += [f"- `{file}`: {len(names)} instance{'s' * (len(names) != 1)}"
              for file, names in sorted(apart.items())]
    lines += ["", WHY.rstrip("\n")]
    # the private CORA files that the instances run: they have no row of their own
    lines += ["", "## Private CORA steps that the instances run", "",
              "A private step (`private/priv_*.m`) is no row of the inventory; its file is tagged and shows here.", ""]
    steps = {}
    for name, s in summary.items():
        for step in s.get("steps", []):
            steps.setdefault(step, []).append(name)
    lines += [f"- `{step}`: {len(names)} instance{'s' * (len(names) != 1)}"
              for step, names in sorted(steps.items())]
    lines += ["", "## Per instance, the rows that are not bit-exact", ""]
    for name, s in summary.items():
        if "rows" not in s:
            continue
        rest = [f"`{k}` ({v})" for k, v in sorted(s["rows"].items()) if v != "oracle"]
        lines += [f"<details><summary>{name}: {s['oracle']}/{s['eligible']}</summary>", "",
                  ", ".join(rest) if rest else "none", "", "</details>", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_table(summary):
    """The table of the README: bit-exact rows per instance."""
    lines = ["| instance | bit-exact vs CORALean | not bit-exact | out of scope (CORALean, CORA.cpp or plumbing) |",
             "|---|---|---|---|"]
    for name, s in summary.items():
        if "skipped" in s:
            lines.append(f"| {name} | - | not measured | - |")
        else:
            lines.append(f"| {name} | {s['oracle']}/{s['eligible']} | {s['eligible'] - s['oracle']} | "
                         f"{s['total'] - s['eligible']} |")
    return "\n".join(lines)


def splice(readme, table, begin=BEGIN, end=END):
    """The README with the text between its markers (the markers are added at the end if missing)."""
    block = f"{begin}\n{table}\n{end}"
    if begin in readme and end in readme:
        head, _, rest = readme.partition(begin)
        _, _, tail = rest.partition(end)
        return head + block + tail
    return readme.rstrip("\n") + "\n\n" + block + "\n"


def render_overall(summary):
    """The sentence of the README summary that quotes the bit-exact share over all instances."""
    done = [s for s in summary.values() if "skipped" not in s]
    x, y = sum(s["oracle"] for s in done), sum(s["eligible"] for s in done)
    return (f"Over the {len(done)} instances, {x} of {y} rows ({100 * x / y:.1f}%) that they execute and "
            "that can be bit-exact are bit-exact against CORALean's `nearest` oracle (the rows summed "
            "per instance; constructors and accessors are left out, see `coverage/README.md`).")


def readme_instance(name, keys):
    """The key of `benchmarks.json` that a row of the README tables names, or None."""
    squeeze = lambda text: re.sub(r"[^a-z0-9]", "", text.lower())  # noqa: E731
    name = ROW_NAMES.get(name, name)
    return next((k for k in keys if squeeze(k) == squeeze(name)), None)


def fill_main_tables(readme, summary):
    """The README with the column `oracle check (rows)` of its main tables filled from the summary,
    cell by cell (the other columns stay); a row of the table that no instance matches is left."""
    out, column = [], None
    for line in readme.split("\n"):
        cells = line.split("|")
        if line.startswith("| instance |") and "oracle check (rows)" in line:
            column = [c.strip() for c in cells].index("oracle check (rows)")
        elif not line.startswith("|"):
            column = None
        elif column is not None and not line.startswith("|---") and len(cells) > column:
            key = readme_instance(cells[1].strip(), summary)
            s = summary.get(key, {})
            if "rows" in s:
                cells[column] = f" {s['oracle']}/{s['eligible']} bit-exact, {s['property']} property "
                line = "|".join(cells)
        out.append(line)
    return "\n".join(out)


# Measuring ---------------------------------------------------------------------------------------

# gcov, not a trace at `detail::Entry`: the private steps (`priv_*`) carry tags and never pass an entry.

def instances(build):
    """The names of the `benchmark` tests of the build, in ctest's order."""
    listing = subprocess.run(["ctest", "--test-dir", str(build), "-N", "-L", "benchmark"], text=True,
                             capture_output=True, check=True).stdout
    return re.findall(r"Test\s+#\d+: benchmark/(\S+)", listing)


def gcov_files(build, root):
    """The files that the counters of the build say executed a line."""
    notes = sorted(Path(build).rglob("*.gcda"))
    executed = set()
    for start in range(0, len(notes), 100):
        out = subprocess.run(["gcov", "--json-format", "--stdout", *map(str, notes[start:start + 100])],
                             text=True, capture_output=True, cwd=build).stdout
        executed.update(parse_gcov(out, root))
    return sorted(executed)


def measure(root, build, names, timeout, committed):
    """`{instance: {"files": [...]}}` or `{"skipped": reason}` from running each on its own. An
    instance that the machine is too small for (ctest: Skipped) keeps its committed measurement."""
    measured = {}
    for name in names:
        for counter in Path(build).rglob("*.gcda"):
            counter.unlink()
        # its own process group, so that a timeout stops the program and not only ctest
        process = subprocess.Popen(["ctest", "--test-dir", str(build), "-R", f"^benchmark/{name}$",
                                    "--timeout", str(timeout)], text=True, stdout=subprocess.PIPE,
                                   start_new_session=True)
        try:
            output, _ = process.communicate(timeout=timeout + 30)
            code = process.returncode
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGKILL)
            code, output = -1, ""
        if code == 0 and "Skipped" in output and name in committed:
            measured[name] = committed[name]
            print(f"{name}: skipped here (not enough memory), the committed measurement stands", flush=True)
            continue
        if code != 0:
            measured[name] = {"skipped": f"failed or over {timeout} s"}
            continue
        measured[name] = {"files": gcov_files(build, root)}
        print(f"{name}: {len(measured[name]['files'])} files", flush=True)
        # what differs from the committed measurement, to find a machine-dependent instance
        old, new = set(committed.get(name, {}).get("files", [])), set(measured[name]["files"])
        if old and old != new:
            print(f"  {name}: only committed {sorted(old - new)}, only measured {sorted(new - old)}")
    return measured


def build_programs(root, preset):
    """Configures and builds the benchmark programs of the preset `coverage`."""
    targets = sorted(p.stem for p in (Path(root) / "examples/cpp/benchmarks").glob("benchmark_*.cpp"))
    subprocess.run(["cmake", "--preset", preset], cwd=root, check=True)
    subprocess.run(["cmake", "--build", "--preset", preset, "--target", *targets], cwd=root, check=True)


# ============================================  MAIN  ============================================ #

def main():
    # --check runs no benchmark: a stale rendering or a measured file that is gone fails it
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="compare the committed files, write nothing")
    parser.add_argument("--remeasure", action="store_true", help="with --check: also run every instance again")
    parser.add_argument("--render-only", action="store_true", help="render the committed measurement")
    parser.add_argument("--only", action="append", default=[], help="measure just this instance")
    parser.add_argument("--timeout", type=int, default=1800, help="seconds per instance (default 1800)")
    parser.add_argument("--build-dir", default="build/coverage")
    args = parser.parse_args()
    # the instances come from a measurement, or from the committed file (--render-only)
    root = REPO
    data = root / "coverage" / "benchmarks.json"
    committed = cov.load_json(data)
    if args.render_only or (args.check and not args.remeasure):
        measured = committed.get("instances", {})
    else:
        build_programs(root, "coverage")
        build = root / args.build_dir
        measured = measure(root, build, args.only or instances(build), args.timeout,
                           committed.get("instances", {}))
        if args.only:
            measured = {**committed.get("instances", {}), **measured}
    # in the order of the committed file, not of ctest, so that the files do not depend on it
    measured = dict(sorted(measured.items()))
    inventory = cov.load_json(root / "coverage" / "cora-inventory.json")
    status = cov.load_json(root / "coverage" / "status.json").get("rows", {})
    lean = cov.load_json(root / "coverage" / "coralean-status.json").get("rows", {})
    summary = summarize(measured, status, inventory["groups"], root, lean)
    # the files to write, by path
    expected = {
        data: json.dumps({"instances": measured}, indent=1, sort_keys=True) + "\n",
        root / "coverage" / "benchmarks.md": render_markdown(summary, lean),
        root / "examples" / "benchmarks" / "README.md": splice(splice(fill_main_tables(
            (root / "examples" / "benchmarks" / "README.md").read_text(encoding="utf-8"), summary),
            render_table(summary)), render_overall(summary), OVERALL_BEGIN, OVERALL_END),
    }
    if args.check:
        stale = [p.relative_to(root).as_posix() for p, text in expected.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        for name in stale:
            print(f"  {name} is stale; run python scripts/coverage/benchmarks.py --render-only")
        # a measured file that is gone is no measurement of the tree any more
        gone = [f"{name}: {file}" for name, entry in measured.items() for file in entry.get("files", [])
                if not (root / file).exists()]
        for line in gone:
            print(f"  {line} no longer exists; measure the instance again (--only)")
        return 1 if stale or gone else 0
    for path, text in expected.items():
        path.write_text(text, encoding="utf-8")
    print("benchmarks: wrote coverage/benchmarks.json, coverage/benchmarks.md and the README table")
    return 0


if __name__ == "__main__":
    sys.exit(main())

