"""coverage - how much of CORA CORA.cpp has, and how much of it is checked: computed from the tree

Syntax:   python scripts/coverage/coverage.py [--check] [--accept-drop <row>]... [--accept-debt] [--summary]
Reads:    coverage/cora-inventory.json (the rows), coverage/coralean-status.json (what CORALean has),
          coverage/out-of-scope.md (the ledger), and the tags of the sources and the tests:
            `// CORA: <path>.m[:method]`       in a source (src/, include/) or a C++ test (`# CORA:` in Python)
            `// CORA.cpp only: <reason>`       in a source that has no CORA file
            `// PROPERTY: <path>.m[:method]`   a test of a stated property on randomized inputs, fixed seeds
            `// ORACLE: <path>.m[:method]`     a test against CORALean (bit-exact at nearest, inside the enclosure)
          `<path>` is the CORA file relative to the CORA root; `:method` names a method of a single-file class.
Writes:   coverage/status.json (each row's status), coverage/README.md and coverage/<group>/<class>.md.
          Never by hand. No committed file holds totals, so PRs on different classes never conflict;
          --summary prints the totals per group and class (CI shows them in the job summary).
Checks:   --check: the files above are current; every tag names an inventory row; every public operation
          has a tag or a `CORA.cpp only:` reason; no row falls below its committed status (`--accept-drop
          <row>` records a drop); no row becomes oracle debt (`--accept-debt` accepts it).
Exit code: 0 if all holds (or the files are written), else 1 with what is wrong.
"""
import argparse
import importlib.util
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import cora_rows  # noqa: E402
import inventory as inventory_file  # noqa: E402

REPO = HERE.parents[1]
STATUSES = ("todo", "untested", "ported", "property", "oracle")
OUT = "out-of-scope"
RANK = {name: i for i, name in enumerate(STATUSES + (OUT,))}
LEAN_HAS = ("proved", "float", "bound")
GROUP_ORDER = cora_rows.GROUPS
ORACLE_HELPER = re.compile(r"oracle_testing")
ORACLE_SKIP = re.compile(r"\bavailable\(\)|\bneeds_oracle\b")
TAG = re.compile(r"^(?://|#) (CORA|PROPERTY|ORACLE): (\S+)\s*$")
ONLY = re.compile(r"^// CORA\.cpp only: \S")
SEED = re.compile(r"Rng\s+\w+\(\s*\d+\s*\)|Rng\(\s*\d+\s*\)|manual_seed\(|default_rng\(\s*\d+|"
                  r"RandomState\(\s*\d+|random\.seed\(|Random\(\s*\d+")
LEAN_NOT_ORACLE = "CORALean has it (proved, float or bound) and CORA.cpp does not yet check against it"

HEADER = """# CORA coverage

How much of CORA CORA.cpp has, and how much of it is checked against CORALean. Generated by
`scripts/coverage/coverage.py` from the tags of the tree; `ctest` fails if these files are stale.

Rows are the method files of CORA's classes ({{commit}}, `cora-inventory.json`). A row is:

| Status | Means |
|---|---|
| `todo` | no source file tags it (`// CORA: <path>.m` in `src/` or `include/`) |
| `untested` | a source tags it, but a C++ test and a Python test do not both declare it |
| `ported` | a C++ test (`// CORA: <path>.m`) and a Python test (`# CORA: <path>.m`) declare it |
| `property` | ported, and a test declares a property on randomized inputs with fixed seeds (`// PROPERTY: <path>.m`) |
| `oracle` | ported, and a test compares it with CORALean (`// ORACLE: <path>.m`, in `tests/**/oracle/` or `test_lean*`): bit-exact at `nearest`, inside the sound enclosure |
| `out-of-scope` | listed in [out-of-scope.md](out-of-scope.md) with a reason |

To raise a row, add the tag with the test that earns it; `python scripts/coverage/coverage.py`
rewrites these files. A single-file class names its method: `// CORA: specification/stl.m:until`
(`:method` is not needed for the file's own name).

`ctest` runs `coverage.py --check` first: a row may not fall below the status in `status.json`
(`--accept-drop <row>` records a drop), and no row may become **oracle debt**, `ported` or
`property` while CORALean has it (`--accept-debt`). `coverage.py --summary` prints the totals.
"""


# ------------------------------------------------------------------------------------ the tree

def load_json(path):
    """A JSON file, {} if there is none."""
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def conventions():
    """The conventions test of the repository, whose notion of an operation file is reused."""
    path = REPO / "tests" / "global" / "test_coding_conventions.py"
    spec = importlib.util.spec_from_file_location("test_coding_conventions", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def rows_of(groups):
    """The rows `(group, class, method)` of an inventory, in its order."""
    return [(g, c, m) for g in GROUP_ORDER for c, ms in groups.get(g, {}).items() for m in ms]


def read(path):
    return path.read_text(encoding="utf-8").replace("\r\n", "\n").split("\n")


def tree_files(root, patterns):
    return sorted({p for pattern in patterns for p in root.glob(pattern) if p.is_file()})


def source_files(root):
    return tree_files(root, ["src/**/*.cpp", "src/**/*.h", "include/**/*.h"])


def test_files(root):
    own = {"test_coverage.py", "test_coding_conventions.py"}
    return [p for p in tree_files(root, ["tests/**/test_*.cpp", "tests/**/test_*.py"])
            if p.name not in own and "competition" not in p.relative_to(root).parts]


def tags_of(root, file, source):
    """The tags of a file: `(kind, path, line)`. A source names its CORA files in its leading
    comment block; a test anywhere, one tag to a line, from the first column."""
    out, lines = [], read(file)
    for number, line in enumerate(lines, 1):
        if source and not line.startswith("//"):
            break
        found = TAG.match(line)
        if found:
            out.append((found.group(1), found.group(2), number))
    return out


def has_only(file):
    """Whether the leading comment block of a source says `CORA.cpp only: <reason>`."""
    block = []
    for line in read(file):
        if not line.startswith("//"):
            break
        block.append(line)
    return any(ONLY.match(line) for line in block)


def resolve(path, groups):
    """`(row key or None, error or None)` of a tag's path: None, None for a file without a row."""
    base, _, method = path.partition(":")
    try:
        row = cora_rows.row_of_path(base)
    except ValueError as error:
        return None, f"{error}" if base.endswith(".m") else f"`{path}` is no CORA file: it ends in .m"
    if row is None:
        return None, None
    group, cls, name = row
    name = method or name or cls
    if method and row[2]:
        return None, f"`{path}`: only a single-file class has `:method`"
    if name not in groups.get(group, {}).get(cls, []):
        return None, f"`{path}` names no inventory row ({group}/{cls}/{name})"
    return cora_rows.key_of(group, cls, name), None


# ----------------------------------------------------------------------------- what the tags say

def scan(root, groups):
    """`(evidence, problems)`: per row key the files `{source, cpp, py, property, oracle}`, and the
    problems of every tag."""
    evidence, problems = {}, []

    def add(key, kind, file):
        evidence.setdefault(key, {}).setdefault(kind, []).append(file.relative_to(root).as_posix())

    for file, source in [(f, True) for f in source_files(root)] + [(f, False) for f in test_files(root)]:
        where = file.relative_to(root).as_posix()
        for kind, path, number in tags_of(root, file, source):
            key, error = resolve(path, groups)
            if error:
                problems.append(f"{where}:{number}: {error}")
            elif source and kind != "CORA":
                problems.append(f"{where}:{number}: `{kind}:` belongs in a test, a source says `CORA:`")
            elif not source and key:
                problems.extend(check_test_tag(root, file, kind, number))
                add(key, "cpp" if file.suffix == ".cpp" else "py", file)
                if kind != "CORA":
                    add(key, kind.lower(), file)
            elif key:
                add(key, "source", file)
    return evidence, problems


def check_test_tag(root, file, kind, number):
    """The conditions a PROPERTY or ORACLE tag puts on its test file."""
    where = f"{file.relative_to(root).as_posix()}:{number}"
    text = "\n".join(read(file))
    if kind == "PROPERTY" and not SEED.search(text):
        return [f"{where}: a PROPERTY test draws its inputs from a fixed seed (`Rng rng(4)`, "
                "`manual_seed(4)`, `default_rng(4)`): none found"]
    if kind == "ORACLE" and "/oracle/" not in "/" + file.relative_to(root).as_posix() \
            and not file.name.startswith("test_lean"):
        return [f"{where}: an ORACLE test is in a folder `oracle/` or named `test_lean*`"]
    if kind == "ORACLE" and not (ORACLE_HELPER.search(text) and ORACLE_SKIP.search(text)):
        return [f"{where}: an ORACLE test uses the helper `oracle_testing` and skips without an oracle "
                "(`test::oracle::available()` in C++, `@needs_oracle` in Python)"]
    return []


def untagged_operations(root, conv):
    """The public operation files that have neither a CORA tag nor a `CORA.cpp only:` reason."""
    out = []
    for file in source_files(root):
        where = file.relative_to(root).as_posix()
        if conv.needs_cora_tag_file(where) and not tags_of(root, file, True) and not has_only(file):
            out.append(f"{where}: names no CORA file: `// CORA: <path>.m` or `// CORA.cpp only: <reason>`")
    return out


def ledger_of(root, groups):
    """`({row key: reason}, problems)` of coverage/out-of-scope.md."""
    keys = {cora_rows.key_of(*row) for row in rows_of(groups)}
    ledger, problems = {}, []
    path = root / "coverage" / "out-of-scope.md"
    for number, line in enumerate(read(path) if path.is_file() else [], 1):
        cells = [c.strip() for c in line.strip().strip("|").split("|")] if line.startswith("| `") else []
        if not cells:
            continue
        key, reason = cells[0].strip("`"), " ".join(cells[1:]).strip()
        where = f"coverage/out-of-scope.md:{number}"
        if key not in keys:
            problems.append(f"{where}: `{key}` is no CORA row (group/class/method)")
        elif key in ledger:
            problems.append(f"{where}: `{key}` is listed twice")
        elif not reason:
            problems.append(f"{where}: `{key}` needs a reason")
        else:
            ledger[key] = reason
    return ledger, problems


def status_of(key, evidence, ledger):
    """The status of a row: todo, untested, ported, property, oracle or out-of-scope."""
    if key in ledger:
        return OUT
    have = evidence.get(key, {})
    if not have.get("source"):
        return "todo"
    if not (have.get("cpp") and have.get("py")):
        return "untested"
    return "oracle" if have.get("oracle") else "property" if have.get("property") else "ported"


def statuses(groups, evidence, ledger):
    return {cora_rows.key_of(*row): status_of(cora_rows.key_of(*row), evidence, ledger)
            for row in rows_of(groups)}


def oracle_debt(status, lean):
    """The rows that are ported or property while CORALean has them."""
    return sorted(k for k, s in status.items()
                  if s in ("ported", "property") and lean.get(k, {}).get("status") in LEAN_HAS)


# ------------------------------------------------------------------------------- the python names

CLASS_RE = re.compile(r'py::class_<([\w:]+)(?:,\s*([\w:]+))?[^>]*>\(\s*m,\s*"(\w+)"')
DEF_RE = re.compile(r'\bm\.def\(\s*"(\w+)"|\.(?:def|def_static|def_property_readonly|def_property|'
                    r'def_readonly|def_readwrite)\(\s*"(\w+)"')


def python_names(root):
    """`({class: {name}}, {class: base}, {module-level name})` of the pybind11 bindings."""
    path = root / "src" / "global" / "python" / "bindings.cpp"
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    oracle_aliases = set(re.findall(r"\busing\s+(\w+)\s*=\s*lean::", text))  # cora.lean's classes
    members, bases, module, current, cpp = {}, {}, set(), None, {}
    events = sorted([(m.start(), "class", m) for m in CLASS_RE.finditer(text)]
                    + [(m.start(), "def", m) for m in DEF_RE.finditer(text)], key=lambda e: e[0])
    for _, kind, m in events:
        if kind == "class" and ("::" in m.group(1) or m.group(1) in oracle_aliases):
            current = None  # a class of another namespace (cora.lean) has its own names
        elif kind == "class":
            current = m.group(3)
            cpp[m.group(1)] = current
            members[current] = set()
            if m.group(2):
                bases[current] = m.group(2)
        elif m.group(1):
            module.add(m.group(1))
            current = None
        elif current:
            members[current].add(m.group(2))
    return members, {c: cpp.get(b) for c, b in bases.items() if cpp.get(b)}, module


def python_name(file, names):
    """The Python name of what a source file implements, or None."""
    members, bases, module = names
    path = Path(file)
    stem, folder = path.stem, path.parent.name
    cls = "".join(w.capitalize() for w in folder.split("_"))
    if stem == folder and cls in members:
        return f"cora.{cls}"
    owner = cls
    while owner in members:
        if stem in members[owner]:
            return f"cora.{cls}.{stem}"
        owner = bases.get(owner)
    return f"cora.{stem}" if stem in module else None


# ------------------------------------------------------------------------------- the tables

def percent(part, whole):
    return f"{100 * part / whole:.0f}%" if whole else "-"


def counts(keys, status, lean):
    """`{status: n, 'rows': n, 'debt': n}` of some rows."""
    out = {s: sum(status[k] == s for k in keys) for s in STATUSES + (OUT,)}
    out["rows"] = len(keys)
    out["debt"] = len(oracle_debt({k: status[k] for k in keys}, lean))
    return out


HEAD = "| {} | CORA methods | todo | untested | ported | property | oracle | out of scope | oracle debt |"


def count_cells(c):
    return (f"{c['rows']} | {c['todo']} | {c['untested']} | {c['ported']} | {c['property']} | "
            f"{c['oracle']} | {c[OUT]} | {c['debt']}")


def group_table(groups, status, lean, link=None):
    """The totals per group as a markdown table, with the share of CORA.cpp's rows."""
    lines = [HEAD.format("Group"), "|---|" + "---|" * 8]
    for g in GROUP_ORDER:
        keys = [cora_rows.key_of(*r) for r in rows_of({g: groups.get(g, {})})]
        lines.append(f"| {link(g) if link else g} | {count_cells(counts(keys, status, lean))} |")
    total = counts(list(status), status, lean)
    lines.append(f"| **all** | {count_cells(total)} |")
    due = total["rows"] - total[OUT]
    lines.append("")
    lines.append(f"{percent(due - total['todo'], due)} of the {due} CORA methods in scope have a source, "
                 f"{percent(due - total['todo'] - total['untested'], due)} are tested in C++ and Python, "
                 f"{percent(total['oracle'], due)} are checked against CORALean; "
                 f"oracle debt {total['debt']}.")
    return "\n".join(lines) + "\n"


def class_tables(groups, status, lean):
    lines = [HEAD.format("Class"), "|---|" + "---|" * 8]
    for g in GROUP_ORDER:
        for c in groups.get(g, {}):
            keys = [cora_rows.key_of(g, c, m) for m in groups[g][c]]
            lines.append(f"| [{g}/{c}]({g}/{c}.md) | {count_cells(counts(keys, status, lean))} |")
    return "\n".join(lines) + "\n"


def class_page(group, cls, groups, status, evidence, lean, names):
    depth = "../../"
    lines = [f"# {group}/{cls}", "",
             f"CORA methods of `{group}/{cls}`; generated by `scripts/coverage/coverage.py`, see "
             "[the statuses](../README.md).", "",
             "| Method | CORA.cpp | C++ | Python | CORALean |", "|---|---|---|---|---|"]
    for m in groups[group][cls]:
        key = cora_rows.key_of(group, cls, m)
        sources = sorted(set(evidence.get(key, {}).get("source", [])))
        cpp = ", ".join(f"[{Path(s).name}]({depth}{s})" for s in sources) or "-"
        py = sorted({n for n in (python_name(s, names) for s in sources) if n})
        lines.append(f"| `{m}` | {status[key]} | {cpp} | {', '.join(f'`{p}`' for p in py) or '-'} "
                     f"| {lean.get(key, {}).get('status', '-')} |")
    return "\n".join(lines) + "\n"


def generate(root, inventory, lean, evidence, ledger, names):
    """Every generated file, `{relative path: text}`, and the statuses."""
    groups = inventory["groups"]
    status = statuses(groups, evidence, ledger)
    files = {}
    commit = inventory.get("cora_commit", "unknown")[:7]
    files["coverage/README.md"] = HEADER.replace("{commit}", f"CORA commit {commit}")
    for g in GROUP_ORDER:
        for c in groups.get(g, {}):
            files[f"coverage/{g}/{c}.md"] = class_page(g, c, groups, status, evidence, lean, names)
    files["coverage/status.json"] = status_text(inventory, status)
    return files, status


def status_text(inventory, status):
    rows = ",\n".join(f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in status.items())
    return (f'{{\n "cora_commit": {json.dumps(inventory.get("cora_commit", "unknown"))},\n'
            f' "rows": {{\n{rows}\n }}\n}}\n')


def summary(groups, status, lean):
    """The totals per group and per class, as markdown."""
    return ("## Coverage\n\n" + group_table(groups, status, lean) + "\n" + class_tables(groups, status, lean))


# ------------------------------------------------------------------------------- the checks

def compare(root, expected, problems):
    """Every generated file is on disk as expected, and nothing else is in the generated folders."""
    stale = [name for name, text in expected.items()
             if not (root / name).is_file() or (root / name).read_text(encoding="utf-8") != text]
    folder = root / "coverage"
    extra = [p.relative_to(root).as_posix() for p in sorted(folder.glob("*/*.md"))
             if p.relative_to(root).as_posix() not in expected] if folder.is_dir() else []
    if stale or extra:
        shown = ", ".join((stale + extra)[:4]) + (" ..." if len(stale + extra) > 4 else "")
        problems.append(f"generated files out of date ({len(stale)} stale, {len(extra)} unexpected: "
                        f"{shown}); rerun `python scripts/coverage/coverage.py`")


def ratchet(status, committed, lean, accept_drop, accept_debt):
    """`(problems, warnings)` of the status against the committed one: no drop, no new oracle debt."""
    problems, warnings = [], []
    rows = committed.get("rows", {})
    for key, old in rows.items():
        new = status.get(key)
        if new is None or RANK[new] >= RANK.get(old, 0):
            continue
        message = f"{key}: {old} -> {new}"
        if key in accept_drop:
            warnings.append(f"{message}: drop accepted")
        else:
            problems.append(f"{message}: coverage may only go up; if the drop is intended, run "
                            f"`python scripts/coverage/coverage.py --accept-drop {key}`")
    was = set(oracle_debt({k: v for k, v in rows.items() if k in status}, lean))
    new = [k for k in oracle_debt(status, lean) if k not in was]
    if new:
        shown = ", ".join(new[:4]) + (" ..." if len(new) > 4 else "")
        message = f"{len(new)} new rows of oracle debt ({shown}): {LEAN_NOT_ORACLE}"
        if accept_debt:
            warnings.append(f"{message}: accepted")
        else:
            problems.append(f"{message}; add the ORACLE test, or run "
                            "`python scripts/coverage/coverage.py --accept-debt`")
    return problems, warnings


def run(root, check=True, accept_drop=(), accept_debt=False, cora=None):
    """Checks the tree at `root` (or rewrites its generated files); `(problems, warnings)`."""
    root = Path(root)
    inventory = load_json(root / "coverage" / "cora-inventory.json")
    if "groups" not in inventory:
        return [f"coverage/cora-inventory.json: missing; run scripts/coverage/inventory.py"], []
    groups, lean = inventory["groups"], load_json(root / "coverage" / "coralean-status.json").get("rows", {})
    evidence, problems = scan(root, groups)
    problems += untagged_operations(root, conventions())
    ledger, more = ledger_of(root, groups)
    problems += more + tagged_but_out_of_scope(evidence, ledger) + tests_without_source(evidence, groups)
    problems += existence_problems(root, cora, inventory)
    expected, status = generate(root, inventory, lean, evidence, ledger, python_names(root))
    committed = load_json(root / "coverage" / "status.json")
    more, warnings = ratchet(status, committed, lean, set(accept_drop), accept_debt)
    problems += more
    if check:
        compare(root, expected, problems)
    if not check and not problems:
        write(root, expected)
    return problems, warnings


def tagged_but_out_of_scope(evidence, ledger):
    return [f"coverage/out-of-scope.md: `{k}` is implemented (a source tags it): remove it from the ledger"
            for k in ledger if evidence.get(k, {}).get("source")]


def tests_without_source(evidence, groups):
    """A test that declares a row no source implements."""
    return [f"{file}: tests `{key}`, which no source file tags (`// CORA: <path>.m`)"
            for key, have in sorted(evidence.items()) if not have.get("source")
            for file in sorted(set(have.get("cpp", []) + have.get("py", [])))]


def existence_problems(root, cora, inventory):
    """With a CORA checkout at the inventory's commit: every tag's file is there."""
    if cora is None or inventory_file.cora_commit(cora) != inventory.get("cora_commit"):
        return []
    out = []
    for file in source_files(root) + test_files(root):
        in_source = file.relative_to(root).parts[0] in ("src", "include")
        for _, path, number in tags_of(root, file, in_source):
            if path.partition(":")[0].endswith(".m") and not (cora / path.partition(":")[0]).is_file():
                out.append(f"{file.relative_to(root).as_posix()}:{number}: {path} is not a file of CORA")
    return out


def write(root, expected):
    """Writes the generated files, and removes the tables of classes that are gone."""
    for path in sorted((root / "coverage").glob("*/*.md")):
        path.unlink()
    for name, text in expected.items():
        target = root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="verify, write nothing")
    parser.add_argument("--accept-drop", action="append", default=[], metavar="ROW",
                        help="accept that ROW (group/class/method) fell below its committed status")
    parser.add_argument("--accept-debt", action="store_true", help="accept rows that become oracle debt")
    parser.add_argument("--summary", action="store_true", help="print the totals as markdown, check nothing")
    args = parser.parse_args()
    if args.summary:
        inventory = load_json(REPO / "coverage" / "cora-inventory.json")
        lean = load_json(REPO / "coverage" / "coralean-status.json").get("rows", {})
        status = load_json(REPO / "coverage" / "status.json").get("rows", {})
        print(summary(inventory["groups"], status, lean), end="")
        return 0
    cora = inventory_file.cora_checkout()
    problems, warnings = run(REPO, args.check, args.accept_drop, args.accept_debt, cora)
    for warning in warnings:
        print(f"WARNING: {warning}")
    for problem in problems:
        print(f"  {problem}")
    if problems:
        print(f"coverage: {len(problems)} problems")
        return 1
    print("coverage: all constraints hold" if args.check else "coverage: wrote coverage/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
